export const LANG_LABELS = {
  ru: "русский",
  en: "english",
};

// Формат ответа ужат под бесплатный лимит Groq (~1 тыс. выходных токенов в
// минуту на весь ключ): по теме — число комментариев и до 6 самых характерных
// номеров вместо полного списка, мнений 1-3 коротких, JSON в одну строку.
// Это примерно вдвое сокращает выход на часть и ускоряет анализ.
export const CHUNK_ANALYZE_SYSTEM = `Ты анализируешь комментарии к YouTube-видео. Тебе дадут список комментариев «№|текст» (№ с 0) и, возможно, темы, уже найденные в других частях обсуждения.

Верни ТОЛЬКО валидный JSON одной строкой, без пробелов и переносов:
{"topics":{"Тема":{"n":N,"ids":[№,№]}},"points":["..."],"notable":[№],"sentiment":{"positive":N,"neutral":N,"negative":N}}

Правила:
- topics: 2-5 тем, которые РЕАЛЬНО обсуждают. Название 2-4 слова, на языке комментариев. Каждый комментарий — максимум в одной теме.
- Если даны «Уже найденные темы» — для подходящих тем используй ТОЧНО эти названия, новую тему заводи только для нового предмета обсуждения.
- Темы — о ЧЁМ пишут (предмет), тональность внутри темы не дроби: не «Похвала монтажу» и «Похвала выпуску», а «Монтаж и качество выпуска».
- Не заводи темы вроде «Прочее», «Разное», «Другие комментарии», «Общие впечатления».
- n — сколько комментариев списка относится к теме; ids — до 6 самых характерных № этой темы.
- points: 1-3 ключевых мнения, каждое до 12 слов.
- notable: 1-2 № самых ярких/смешных/спорных комментариев.
- sentiment: сколько комментариев позитивных / нейтральных / негативных, сумма = числу комментариев. Спам, ссылки, «👍» — нейтральные.
- № — только числа из списка. Без пояснений и markdown.`;

export function chunkUser(comments, knownTopics = []) {
  // Автора не передаём: для разбивки на темы он не нужен, а это ~12% входа.
  const lines = comments
    .map((c, i) => `${i}|${(c.text || "").slice(0, 300).replace(/\s+/g, " ")}`)
    .join("\n");
  const known = knownTopics.length ? `Уже найденные темы: ${knownTopics.join("; ")}\n\n` : "";
  return `${known}Комментариев: ${comments.length}\n\n${lines}`;
}

export const FINAL_SYSTEM = `Ты делаешь итоговую сводку обсуждения под YouTube-видео по результатам анализа кусками.

Тебе дадут: темы с количеством комментариев, ключевые мнения, тональность (positive/neutral/negative в сумме по всем комментариям), и несколько самых ярких комментариев с их текстами.

Верни ТОЛЬКО текст сводки — сплошной абзац, БЕЗ JSON-обёртки, без markdown, без списков, без эмодзи, на языке выходного формата (до 380 символов): о чём в основном пишут, радуются/спорят/жалуются, главный вывод.`;

export function finalUser({ topics, points, sentiment, notableComments, lang }) {
  const topicLines = Object.entries(topics)
    .map(([name, n]) => `- ${name}: ${n}`)
    .join("\n") || "- (тем не выделено)";
  const pointsText = points.map((p) => `- ${p}`).join("\n") || "- (нет)";
  const notableText =
    notableComments.map((c, i) => `${i + 1}. «${(c.text || "").slice(0, 220)}»`).join("\n") ||
    "- (нет)";
  return `Выходной язык: ${LANG_LABELS[lang] || "русский"}

Темы:
${topicLines}

Ключевые мнения:
${pointsText}

Тональность: positive=${sentiment.positive}, neutral=${sentiment.neutral}, negative=${sentiment.negative} (всего ${sentiment.positive + sentiment.neutral + sentiment.negative})

Яркие комментарии:
${notableText}`;
}

export const SEARCH_SYSTEM = `Ты фильтруешь комментарии YouTube по запросу пользователя.
Тебе дадут запрос и список комментариев вида [{"id":число,"t":"текст"},...].

Верни ТОЛЬКО JSON: {"ids":[числа],"why":"короткое пояснение на языке запроса (max 120 символов)"}

Правила:
- Выбирай комментарии, реально релевантные запросу ПО СМЫСЛУ (не только точное совпадение слов): синонимы, близкие мнения, примеры.
- Не более 15 ids. Если релевантных нет — ids пустой.
- ids — только числа из списка.`;

export function searchUser(query, comments) {
  const list = comments
    .slice(0, 400)
    .map((c, i) => `{"id":${i},"t":${JSON.stringify((c.text || "").slice(0, 160))}}`)
    .join(",");
  return `Запрос пользователя: ${query}\n\nКомментарии: [${list}]`;
}

